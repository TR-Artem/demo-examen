def norm(rows):
    out = []
    for row in rows:
        clean = []
        for val in row:
            if isinstance(val, float):
                val = round(val, 2)
            elif val is None:
                val = ""
            elif isinstance(val, str):
                val = val.strip()
            clean.append(val)
        out.append(tuple(clean))
    return out


def fetch(con, sql):
    cur = con.execute(sql)
    cols = [d[0] for d in cur.description] if cur.description else []
    return cols, norm(cur.fetchall())


def rows_equal(actual, expected):
    """Сравнивает результаты, прощая разницу в округлении копеек."""
    if len(actual) != len(expected):
        return False
    for row_a, row_b in zip(actual, expected):
        if len(row_a) != len(row_b):
            return False
        for a, b in zip(row_a, row_b):
            if isinstance(a, float) and isinstance(b, float):
                if abs(a - b) > 0.011:
                    return False
            elif a != b:
                return False
    return True


def render_table(cols, rows):
    if not cols:
        return "(запрос не вернул столбцы)"
    shown = rows[:40]
    # Число столбцов берём по максимуму: пользователь мог вернуть меньше, чем эталон
    n = max([len(cols)] + [len(r) for r in shown])
    header = list(cols) + [""] * (n - len(cols))
    widths = [len(str(c)) for c in header]
    for row in shown:
        for i in range(n):
            val = row[i] if i < len(row) else ""
            widths[i] = max(widths[i], min(len(str(val)), 34))
    widths = [min(w, 34) for w in widths]

    def line(values):
        vals = list(values) + [""] * (n - len(values))
        return " | ".join(str(v)[:widths[i]].ljust(widths[i])
                          for i, v in enumerate(vals))
    out = [line(header), "-+-".join("-" * w for w in widths)]
    out += [line(r) for r in shown]
    if len(rows) > 40:
        out.append(f"... и ещё {len(rows) - 40} строк")
    return "\n".join(out)


