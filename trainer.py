def scrollable(parent):
    """Возвращает прокручиваемый фрейм."""
    canvas = tk.Canvas(parent, bg=BG, highlightthickness=0)
    bar = ttk.Scrollbar(parent, orient="vertical", command=canvas.yview)
    inner = ttk.Frame(canvas)
    canvas.configure(yscrollcommand=bar.set)
    bar.pack(side="right", fill="y")
    canvas.pack(side="left", fill="both", expand=True)
    win = canvas.create_window((0, 0), window=inner, anchor="nw")

    def on_inner_config(_e=None):
        canvas.configure(scrollregion=canvas.bbox("all"))
    def on_canvas_config(_e=None):
        canvas.itemconfig(win, width=canvas.winfo_width())
    inner.bind("<Configure>", on_inner_config)
    canvas.bind("<Configure>", on_canvas_config)

    def wheel(event):
        canvas.yview_scroll(int(-1 * (event.delta / 120)), "units")
    def enter(_e):
        canvas.bind_all("<MouseWheel>", wheel)
    def leave(_e):
        canvas.unbind_all("<MouseWheel>")
    inner.bind("<Enter>", enter)
    inner.bind("<Leave>", leave)
    return inner


def label(parent, text, **kw):
    opts = dict(background=BG, foreground=INK, font=("Segoe UI", 10),
                wraplength=900, justify="left")
    opts.update(kw)
    return tk.Label(parent, text=text, **opts)


def card(parent, title_text):
    frame = ttk.LabelFrame(parent, text=title_text, padding=10)
    frame.pack(fill="x", padx=12, pady=6)
    return frame


