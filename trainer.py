    def check_sql(self):
        t = self.sql_current
        if not t:
            return
        user_sql = self.sql_input.get("1.0", "end").strip()
        if not user_sql:
            self.sql_out("Напиши SQL-запрос в поле выше.")
            return
        mode = t.get("mode", "select")
        try:
            if mode == "select":
                ref = fresh_db()
                _, expected = fetch(ref, t["expected"])
                ref.close()
                con = fresh_db()
                cols, actual = fetch(con, user_sql)
                con.close()
            else:
                ref = fresh_db()
                ref.executescript(t["expected"])
                _, expected = fetch(ref, t["verify"])
                ref.close()
                con = fresh_db()
                con.executescript(user_sql)
                cols, actual = fetch(con, t["verify"])
                con.close()
        except sqlite3.Error as err:
            self.sql_out(f"ОШИБКА SQL: {err}\n\n"
                         "Проверь названия таблиц/столбцов, кавычки и порядок предложений.\n"
                         "Структуру БД можно посмотреть кнопкой слева.")
            return
        except Exception as err:                      # noqa: BLE001 - учебный режим
            self.sql_out(f"Ошибка: {err}")
            return

        if rows_equal(actual, expected):
            self.sql_out("✓ ВЕРНО! Запрос вернул эталонный результат.\n\n"
                         + render_table(cols, actual))
            if t["id"] not in self.state["sql_done"]:
                self.state["sql_done"].append(t["id"])
                save_state(self.state)
                idx = SQL_TASKS.index(t)
                self.sql_list.delete(idx)
                self.sql_list.insert(idx, "✓ " + t["title"])
                self.refresh_progress_tab()
        else:
            msg = ["✗ ПОКА НЕВЕРНО — результат отличается от эталонного.\n",
                   "Твой результат:", render_table(cols, actual),
                   "\nОжидаемый результат:", render_table(cols, expected),
                   "\nПодсказка: " + t["hint"]]
            self.sql_out("\n".join(msg))

