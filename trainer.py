def load_state():
    state = json.loads(json.dumps(DEFAULT_STATE))
    if STATE_FILE.exists():
        try:
            saved = json.loads(STATE_FILE.read_text(encoding="utf-8"))
            for key, value in saved.items():
                state[key] = value
        except (json.JSONDecodeError, OSError):
            pass
    if not isinstance(state.get("practical_done"), list):
        state["practical_done"] = []
    return state


def save_state(state):
    try:
        STATE_FILE.write_text(json.dumps(state, ensure_ascii=False, indent=2),
                              encoding="utf-8")
    except OSError as err:
        messagebox.showwarning("Не удалось сохранить прогресс", str(err))


def mark_active(state):
    today = date.today().isoformat()
    if today not in state["days_active"]:
        state["days_active"].append(today)
        save_state(state)


