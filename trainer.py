    def start_quiz(self, count):
        topic = self.quiz_topic.get()
        pool = [x for x in QUIZ if topic == "Все темы" or x["topic"] == topic]
        if not pool:
            return
        self.quiz_queue = random.sample(pool, min(count, len(pool)))
        if len(self.quiz_queue) < count:
            self.quiz_queue += random.choices(pool, k=count - len(self.quiz_queue))
        self.quiz_session = {"asked": 0, "correct": 0}
        self.quiz_feedback_set("Тест запущен. Выбирай вариант и жми «Ответить».")
        self.next_quiz_question(reset=True)

    def quiz_feedback_set(self, text):
        self.quiz_feedback.config(state="normal")
        self.quiz_feedback.delete("1.0", "end")
        self.quiz_feedback.insert("1.0", text)
        self.quiz_feedback.config(state="disabled")

    def next_quiz_question(self, reset=False):
        if not reset and not self.quiz_queue:
            self.quiz_current = None
            self.quiz_question.config(text="Тест завершён! Запусти новый.")
            self.quiz_answer_btn.config(state="disabled")
            self.quiz_next_btn.config(state="disabled")
            self.quiz_feedback_set(
                f"Результат: {self.quiz_session['correct']} из {self.quiz_session['asked']} "
                f"({self.quiz_session['correct'] / max(1, self.quiz_session['asked']) * 100:.0f}%). "
                "Слабые места смотри в «Мой прогресс» → повтори теорию.\n\n"
                "Закрепи тему кнопкой «⌨ Практика по теме»: там нужно написать код "
                "и пройти автопроверку.")
            return
        self.quiz_current = self.quiz_queue.pop(0)
        item = self.quiz_current
        self.quiz_question.config(text=item["q"])
        self.quiz_var.set(-1)
        for i, rb in enumerate(self.quiz_radios):
            rb.config(text=f"   {chr(65 + i)}. {item['opts'][i]}", state="normal")
        self.quiz_answer_btn.config(state="normal")
        self.quiz_next_btn.config(state="disabled")
        self.quiz_feedback_set("")
        left = len(self.quiz_queue) + 1
        self.quiz_score.config(
            text=f"Осталось {left}  ·  верно {self.quiz_session['correct']}/{self.quiz_session['asked']}")

    def check_quiz_answer(self):
        if self.quiz_current is None or self.quiz_var.get() < 0:
            messagebox.showinfo("Выбери ответ", "Сначала выбери один из вариантов.")
            return
        item = self.quiz_current
        chosen = self.quiz_var.get()
        correct = chosen == item["ans"]
        self.quiz_session["asked"] += 1
        self.quiz_session["correct"] += int(correct)
        st = self.state["quiz"]
        st["asked"] += 1
        st["correct"] += int(correct)
        topic_stat = st["by_topic"].setdefault(item["topic"], {"asked": 0, "correct": 0})
        topic_stat["asked"] += 1
        topic_stat["correct"] += int(correct)
        save_state(self.state)
        for i, rb in enumerate(self.quiz_radios):
            rb.config(state="disabled")
            if i == item["ans"]:
                rb.config(fg=ACCENT_DARK, font=("Segoe UI", 11, "bold"))
            elif i == chosen:
                rb.config(fg=RED)
            else:
                rb.config(fg=INK)
        self.quiz_feedback_set(
            ("ВЕРНО ✓  " if correct else "НЕВЕРНО ✗  ")
            + f"Правильный ответ: {chr(65 + item['ans'])}. {item['opts'][item['ans']]}\n\n"
            + item["explain"])
        self.quiz_answer_btn.config(state="disabled")
        self.quiz_next_btn.config(state="normal")
        self.quiz_score.config(
            text=f"Осталось {len(self.quiz_queue)}  ·  верно {self.quiz_session['correct']}/{self.quiz_session['asked']}")
        self.refresh_progress_tab()

