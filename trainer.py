    def save_thresholds(self):
        self.state["thresholds"] = {k: int(v.get()) for k, v in self.threshold_vars.items()}
        save_state(self.state)
        self.update_exam_score()

    def update_exam_score(self):
        score = sum(w for i, _text, w in self.exam_items if self.exam_vars[i].get())
        self.state["exam_checks"] = [i for i, v in self.exam_vars.items() if v.get()]
        save_state(self.state)
        percent = score / MAX_SCORE * 100
        th = self.state["thresholds"]
        grade = 2
        for mark in (3, 4, 5):
            if percent >= th[str(mark)]:
                grade = mark
        names = {2: "2 (не сдано)", 3: "3 (удовл.)", 4: "4 (хор.)", 5: "5 (отл.)"}
        self.exam_score_label.config(text=f"Баллы: {score} / {MAX_SCORE}  ({percent:.0f}%)")
        self.exam_grade_label.config(
            text=f"Оценка: {names[grade]}",
            foreground=ACCENT_DARK if grade >= 4 else RED)
        need4 = max(0, int(th["4"] / 100 * MAX_SCORE + 0.999) - score)
        need5 = max(0, int(th["5"] / 100 * MAX_SCORE + 0.999) - score)
        self.exam_need_label.config(
            text=f"До «4»: {need4} б.   До «5»: {need5} б.\n"
                 f"Самые «жирные»: Задание 3 (25), Задание 4 (25), Задание 5 (25).")

